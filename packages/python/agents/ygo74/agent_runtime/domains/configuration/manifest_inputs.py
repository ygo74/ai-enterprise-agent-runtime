"""Typed YAML input contracts for agent and skill manifests."""

from __future__ import annotations

from typing import Annotated

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    StrictBool,
    StrictStr,
    StringConstraints,
    model_validator,
)
from ygo74.agent_runtime.domains.security.operations import OperationType, RiskLevel

ManifestText = Annotated[
    StrictStr, StringConstraints(strip_whitespace=True, min_length=1, pattern=r"\S")
]


def _skill_manifest_json_schema(schema: dict[str, object]) -> None:
    """Require a local server's tool allow-list in the editor schema.

    Args:
        schema (dict[str, object]): JSON Schema document generated by Pydantic.
    """
    schema["allOf"] = [
        {
            "if": {
                "properties": {"mcp_server": {"type": "string"}},
                "required": ["mcp_server"],
            },
            "then": {
                "required": ["mcp_tools"],
                "properties": {"mcp_tools": {"type": "array", "minItems": 1}},
            },
        },
    ]


class OperationManifestInput(BaseModel):
    """The fixed YAML shape of a skill's operation declaration."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    type: OperationType
    risk: RiskLevel
    permission: ManifestText
    confirmation_required: StrictBool


class SkillManifestInput(BaseModel):
    """The fixed YAML fields accepted for one skill package."""

    model_config = ConfigDict(
        extra="forbid", frozen=True, json_schema_extra=_skill_manifest_json_schema
    )

    tool_name: ManifestText
    implementation: ManifestText
    description: ManifestText
    operation: OperationManifestInput
    mcp_server: ManifestText | None = None
    mcp_tools: tuple[ManifestText, ...] = ()

    @model_validator(mode="after")
    def _require_tools_for_explicit_server(self) -> SkillManifestInput:
        """Require aliases when a skill explicitly selects an MCP server."""
        if self.mcp_server and not self.mcp_tools:
            raise ValueError(
                "mcp_tools must contain at least one alias when mcp_server is declared"
            )
        return self


class AgentManifestInput(BaseModel):
    """The fixed YAML fields accepted for one agent."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    name: ManifestText
    description: ManifestText
    mcp_server: ManifestText | None = None
    skills: tuple[ManifestText, ...] = Field(min_length=1)
