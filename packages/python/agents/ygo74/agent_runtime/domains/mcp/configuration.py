CapabilityT = TypeVar("CapabilityT", bound=StrEnum)
_SECRET_REFERENCE = re.compile(r"^\$\{(?P<name>[A-Za-z_][A-Za-z0-9_]*)\}$")
_HEADER_NAME = re.compile(r"^[!#$%&'*+.^_`|~0-9A-Za-z-]+$")
_HEADER_TOKEN = re.compile(r"\{\{(?P<name>[^{}]+)\}\}")
_HEADER_VALUE_PATTERN = (
    r"^(?:\$\{[A-Za-z_][A-Za-z0-9_]*\}|"
    r"(?:(?!\$\{|\{\{|\}\}|\r|\n)[\s\S]|"
    r"\{\{(?:USER_ID|USER_EMAIL|USER_NAME|USER_ROLES|REQUEST_ID|CONVERSATION_ID|SESSION_ID)\}\})*)$"
)
_SecretReference = Annotated[
    StrictStr, StringConstraints(pattern=r"^\$\{[A-Za-z_][A-Za-z0-9_]*\}$")
]
_ConfigurationText = Annotated[
    StrictStr, StringConstraints(strip_whitespace=True, min_length=1, pattern=r"\S")
]


class McpAuthenticationMode(StrEnum):
    """Authentication method selected for an HTTP MCP server."""

    NONE = "none"
    API_KEY = "api_key"
    OAUTH = "oauth"
    OAUTH_ON_BEHALF_OF = "oauth_on_behalf_of"


class McpHeaderContextToken(StrEnum):
    """Request-scoped values that configured MCP headers may interpolate."""

    USER_ID = "USER_ID"
    USER_EMAIL = "USER_EMAIL"
    USER_NAME = "USER_NAME"
    USER_ROLES = "USER_ROLES"
    REQUEST_ID = "REQUEST_ID"
    CONVERSATION_ID = "CONVERSATION_ID"
    SESSION_ID = "SESSION_ID"


class McpApiKeyInput(BaseModel):
    """YAML fields for a single API-key header.

    Args:
        header_name (_ConfigurationText): HTTP header receiving the resolved key.
        value (_SecretReference): Environment reference containing the key.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    header_name: _ConfigurationText
    value: _SecretReference


class McpOAuthInput(BaseModel):
    """YAML fields for an OAuth client using the runtime's loopback flow.

    Args:
        client_id (_ConfigurationText): Pre-registered OAuth client identity.
        client_secret (_SecretReference): Environment reference containing the client secret.
        callback_port (StrictInt): Local loopback port used for the authorization redirect.
        scopes (tuple[_ConfigurationText, ...]): Requested scopes pinned by the runtime.
        token_file (_ConfigurationText): Token storage path, relative to the delivered root by default.
        client_name (_ConfigurationText): Human-readable OAuth client label.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    client_id: _ConfigurationText
    client_secret: _SecretReference
    callback_port: StrictInt = Field(default=8765, ge=1, le=65535)
    scopes: tuple[_ConfigurationText, ...] = Field(min_length=1)
    token_file: _ConfigurationText = ".secrets/mcp-token.json"
    client_name: _ConfigurationText = "MCP client"


def _delegated_oauth_json_schema(schema: dict[str, Any]) -> None:
    """Show complete client settings and HTTPS endpoint requirements in editor schemas.

    Args:
        schema (dict[str, Any]): JSON Schema document generated by Pydantic.
    """
    schema["properties"]["token_url"]["pattern"] = r"^https://\S+$"
    schema["allOf"] = [
        {
            "if": {
                "anyOf": [
                    {"required": ["token_url"]},
                    {"required": ["client_id"]},
                    {"required": ["client_secret"]},
                ]
            },
            "then": {"required": ["token_url", "client_id", "client_secret"]},
        }
    ]


class McpDelegatedOAuthInput(BaseModel):
    """YAML settings for OAuth on-behalf-of exchange.

    Args:
        token_url (_ConfigurationText | None): HTTPS token endpoint for the runtime source or a custom factory.
        client_id (_ConfigurationText | None): OAuth client identity for the exchange source.
        client_secret (_SecretReference | None): Environment reference for the OAuth client credential.
        audience (_ConfigurationText): Downstream MCP resource identifier.
        scopes (tuple[_ConfigurationText, ...]): Optional scopes requested from the delegated-token source.
    """

    model_config = ConfigDict(
        extra="forbid", frozen=True, json_schema_extra=_delegated_oauth_json_schema
    )

    token_url: _ConfigurationText | None = None
    client_id: _ConfigurationText | None = None
    client_secret: _SecretReference | None = None
    audience: _ConfigurationText
    scopes: tuple[_ConfigurationText, ...] = ()

    @model_validator(mode="after")
    def _validate_client_settings(self) -> McpDelegatedOAuthInput:
        """Require complete client settings and a TLS-protected token endpoint."""
        client_settings = (self.token_url, self.client_id, self.client_secret)
        if any(value is not None for value in client_settings) and not all(
            value is not None for value in client_settings
        ):
            raise ValueError(
                "token_url, client_id, and client_secret must be configured together"
            )
        if self.token_url is not None:
            parsed_url = urlsplit(self.token_url)
            if (
                parsed_url.scheme.casefold() != "https"
                or not parsed_url.hostname
                or parsed_url.username is not None
                or parsed_url.password is not None
            ):
                raise ValueError(
                    "authentication_oauth_on_behalf_of.token_url must be an HTTPS URL without embedded credentials"
                )
        return self


class McpNetworkInput(BaseModel):
    """Optional network settings for a streamable HTTP connection.

    Args:
        proxy_url (_ConfigurationText | None): Optional credential-free HTTP or HTTPS proxy URL.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    proxy_url: _ConfigurationText | None = None


def _mcp_server_json_schema(schema: dict[str, Any]) -> None:
    """Reflect transport and authentication dependencies in editor validation.

    Args:
        schema (dict[str, Any]): JSON Schema document generated by Pydantic.
    """
    schema["allOf"] = [
        {
            "if": {
                "properties": {"transport": {"const": "http"}},
                "required": ["transport"],
            },
            "then": {
                "required": ["url"],
                "properties": {"url": {"type": "string", "minLength": 1}},
            },
        },
        {
            "if": {
                "properties": {"transport": {"const": "stdio"}},
                "required": ["transport"],
            },
            "then": {
                "required": ["command"],
                "properties": {"command": {"type": "string", "minLength": 1}},
            },
        },
        {
            "if": {
                "properties": {"authentication_mode": {"const": "api_key"}},
                "required": ["authentication_mode"],
            },
            "then": {
                "required": ["authentication_api_key"],
                "not": {"required": ["authentication_oauth"]},
            },
        },
        {
            "if": {
                "properties": {"authentication_mode": {"const": "oauth"}},
                "required": ["authentication_mode"],
            },
            "then": {
                "required": ["authentication_oauth"],
                "not": {"required": ["authentication_api_key"]},
            },
        },
        {
            "if": {
                "properties": {"authentication_mode": {"const": "oauth_on_behalf_of"}},
                "required": ["authentication_mode"],
            },
            "then": {
                "required": ["authentication_oauth_on_behalf_of"],
                "not": {
                    "anyOf": [
                        {"required": ["authentication_api_key"]},
                        {"required": ["authentication_oauth"]},
                    ]
                },
            },
        },
        {
            "if": {
                "anyOf": [
                    {"not": {"required": ["authentication_mode"]}},
                    {"properties": {"authentication_mode": {"const": "none"}}},
                ]
            },
            "then": {
                "not": {
                    "anyOf": [
                        {"required": ["authentication_api_key"]},
                        {"required": ["authentication_oauth"]},
                        {"required": ["authentication_oauth_on_behalf_of"]},
                    ]
                }
            },
        },
        {
            "if": {
                "properties": {"transport": {"const": "stdio"}},
                "required": ["transport"],
            },
            "then": {
                "not": {
                    "anyOf": [
                        {
                            "properties": {
                                "authentication_mode": {
                                    "enum": ["api_key", "oauth", "oauth_on_behalf_of"]
                                }
                            },
                            "required": ["authentication_mode"],
                        },
                        {
                            "properties": {
                                "network": {
                                    "properties": {"proxy_url": {"type": "string"}},
                                    "required": ["proxy_url"],
                                }
                            },
                            "required": ["network"],
                        },
                        {
                            "properties": {"headers": {"minProperties": 1}},
                            "required": ["headers"],
                        },
                    ]
                }
            },
        },
    ]
    schema["properties"]["headers"] = {
        "type": "object",
        "propertyNames": {"pattern": r"^[!#$%&'*+.^_`|~0-9A-Za-z-]+$"},
        "additionalProperties": {"type": "string", "pattern": _HEADER_VALUE_PATTERN},
    }


class McpServerConfigurationInput(BaseModel):
    """Strict typed representation of one MCP server YAML file.

    Args:
        server (_ConfigurationText | None): Optional server identity, defaulting to the file name.
        transport (McpTransport): HTTP or stdio transport selected for the server.
        url (_ConfigurationText | None): HTTP endpoint when using HTTP transport.
        command (_ConfigurationText | None): Executable when using stdio transport.
        args (tuple[StrictStr, ...]): Arguments passed to a stdio executable.
        env (dict[StrictStr, StrictStr]): Additional environment passed to a stdio executable.
        capabilities (tuple[_ConfigurationText, ...]): Application capabilities declared by the server.
        tools (dict[_ConfigurationText, _ConfigurationText]): Logical aliases and remote tool names.
        dialect (_ConfigurationText): Protocol dialect selected by the application.
        read_only_variable (_ConfigurationText | None): Deployment variable interpreted by the host.
        request_timeout_seconds (StrictInt): HTTP request and protocol session timeout.
        headers (dict[StrictStr, StrictStr]): HTTP headers containing literals, env references, or context tokens.
        authentication_mode (McpAuthenticationMode): Selected HTTP authentication mechanism.
        authentication_api_key (McpApiKeyInput | None): API-key header settings when selected.
        authentication_oauth (McpOAuthInput | None): OAuth client settings when selected.
        authentication_oauth_on_behalf_of (McpDelegatedOAuthInput | None): Audience and scopes for delegated OAuth.
        network (McpNetworkInput): HTTP proxy options.
    """

    model_config = ConfigDict(
        extra="forbid", frozen=True, json_schema_extra=_mcp_server_json_schema
    )

    server: _ConfigurationText | None = None
    transport: McpTransport
    url: _ConfigurationText | None = None
    command: _ConfigurationText | None = None
    args: tuple[StrictStr, ...] = ()
    env: dict[StrictStr, StrictStr] = Field(default_factory=dict)
    capabilities: tuple[_ConfigurationText, ...] = Field(min_length=1)
    tools: dict[_ConfigurationText, _ConfigurationText] = Field(default_factory=dict)
    dialect: _ConfigurationText = "native"
    read_only_variable: _ConfigurationText | None = None
    request_timeout_seconds: StrictInt = Field(default=30, ge=1)
    headers: dict[StrictStr, StrictStr] = Field(default_factory=dict)
    authentication_mode: McpAuthenticationMode = McpAuthenticationMode.NONE
    authentication_api_key: McpApiKeyInput | None = None
    authentication_oauth: McpOAuthInput | None = None
    authentication_oauth_on_behalf_of: McpDelegatedOAuthInput | None = None
    network: McpNetworkInput = Field(default_factory=McpNetworkInput)

    @model_validator(mode="after")
    def _validate_transport_settings(self) -> McpServerConfigurationInput:
        """Reject missing endpoint and transport-incompatible settings."""
        if self.transport is McpTransport.HTTP and not self.url:
            raise ValueError("HTTP transport requires a non-empty url")
        if self.transport is McpTransport.STDIO and not self.command:
            raise ValueError("stdio transport requires a non-empty command")
        if self.transport is McpTransport.STDIO and (
            self.authentication_mode is not McpAuthenticationMode.NONE
            or self.authentication_api_key is not None
            or self.authentication_oauth is not None
            or self.authentication_oauth_on_behalf_of is not None
            or self.network.proxy_url is not None
            or self.headers
        ):
            raise ValueError(
                "authentication, headers, and network proxy settings require HTTP transport"
            )
        McpNetworkSettings(proxy_url=self.network.proxy_url)
        self._validate_headers()
        expected = {
            McpAuthenticationMode.NONE: (None, None, None),
            McpAuthenticationMode.API_KEY: (self.authentication_api_key, None, None),
            McpAuthenticationMode.OAUTH: (None, self.authentication_oauth, None),
            McpAuthenticationMode.OAUTH_ON_BEHALF_OF: (
                None,
                None,
                self.authentication_oauth_on_behalf_of,
            ),
        }[self.authentication_mode]
        if (
            self.authentication_api_key,
            self.authentication_oauth,
            self.authentication_oauth_on_behalf_of,
        ) != expected:
            raise ValueError(
                f"authentication settings do not match mode {self.authentication_mode.value!r}"
            )
        if self.authentication_mode is not McpAuthenticationMode.NONE and any(
            name.casefold() == "authorization" for name in self.headers
        ):
            raise ValueError(
                "headers.Authorization conflicts with configured authentication"
            )
        if self.authentication_api_key is not None and any(
            name.casefold() == self.authentication_api_key.header_name.casefold()
            for name in self.headers
        ):
            raise ValueError("headers contains the configured API-key header")
        return self

    def _validate_headers(self) -> None:
        """Validate header names and interpolation syntax without exposing values."""
        names: set[str] = set()
        for name, value in self.headers.items():
            normalized_name = name.casefold()
            if not _HEADER_NAME.fullmatch(name) or normalized_name in names:
                raise ValueError(
                    "headers contains an invalid or duplicate HTTP header name"
                )
            names.add(normalized_name)
            if "\r" in value or "\n" in value:
                raise ValueError(f"headers.{name} must not contain a line break")
            env_reference = _SECRET_REFERENCE.fullmatch(value)
            if "${" in value and env_reference is None:
                raise ValueError(
                    f"headers.{name} environment references must occupy the entire value"
                )
            tokens = tuple(_HEADER_TOKEN.finditer(value))
            if ("{{" in value or "}}" in value) and not tokens:
                raise ValueError(f"headers.{name} contains a malformed context token")
            for token in tokens:
                try:
                    McpHeaderContextToken(token.group("name"))
                except ValueError as error:
                    raise ValueError(
                        f"headers.{name} contains an unsupported context token"
                    ) from error
            remainder = _HEADER_TOKEN.sub("", value)
            if "{{" in remainder or "}}" in remainder:
                raise ValueError(f"headers.{name} contains a malformed context token")


@dataclass(frozen=True, slots=True)
class McpApiKeySettings:
    """Resolved API-key header settings with a redacted secret value.

    Args:
        header_name (str): HTTP header receiving the API key.
        value (SecretStr): Resolved key whose representation is redacted.
    """

    header_name: str
    value: SecretStr


@dataclass(frozen=True, slots=True)
class McpOAuthSettings:
    """Resolved OAuth client configuration; the client secret is redacted.

    Args:
        client_id (str): Pre-registered OAuth client identity.
        client_secret (SecretStr): Resolved secret whose representation is redacted.
        callback_port (int): Local loopback port used for the authorization redirect.
        scopes (tuple[str, ...]): Requested scopes pinned by the runtime.
        token_file (Path): File that stores issued OAuth tokens.
        client_name (str): Human-readable OAuth client label.
    """

    client_id: str
    client_secret: SecretStr
    callback_port: int
    scopes: tuple[str, ...]
    token_file: Path
    client_name: str


# Keep the name introduced by the first Issue 27 implementation available while
# callers adopt the generic OAuth token-exchange settings contract.
McpDelegatedOAuthSettings = OAuthTokenExchangeSettings


@dataclass(frozen=True, slots=True, repr=False)
class McpServerConfiguration(Generic[CapabilityT]):
    """Validated binding and connection settings for one configured MCP server.

    Args:
        binding (McpServerBinding[CapabilityT]): Validated endpoint and tool mapping.
        request_timeout_seconds (int): Request and protocol-session timeout.
        authentication_mode (McpAuthenticationMode): Selected HTTP authentication mode.
        api_key (McpApiKeySettings | None): Optional API-key header with redacted value.
        oauth (McpOAuthSettings | None): Optional OAuth configuration with redacted client secret.
        network (McpNetworkSettings): HTTP proxy settings.
        delegated_oauth (OAuthTokenExchangeSettings | None): Optional downstream audience, scopes, and exchange-client settings.
        headers (Mapping[str, str]): Resolved headers and deferred context templates, redacted in representations.
    """

    binding: McpServerBinding[CapabilityT]
    request_timeout_seconds: int
    authentication_mode: McpAuthenticationMode
    api_key: McpApiKeySettings | None
    oauth: McpOAuthSettings | None
    network: McpNetworkSettings
    delegated_oauth: OAuthTokenExchangeSettings | None = None
    headers: Mapping[str, str] = field(
        default_factory=lambda: _RedactedMapping({}), repr=False
    )

    def __repr__(self) -> str:
        """Return a safe representation that never includes credentials or proxy URLs."""
        return (
            f"{type(self).__name__}(server={self.binding.server!r}, "
            f"transport={self.binding.transport.value!r}, "
            f"authentication_mode={self.authentication_mode.value!r}, "
            f"request_timeout_seconds={self.request_timeout_seconds!r}, "
            f"proxy_configured={self.network.proxy_url is not None})"
        )


class McpServerConfigurationLoader(Generic[CapabilityT]):
    """Load one schema-validated MCP server file and resolve credential references.

    Args:
        capabilities (type[CapabilityT]): Application capabilities valid in server declarations.
        environment (Mapping[str, str] | None): Environment source used for secret references.
        error_factory (ErrorFactory): Callback that builds the domain error for this failure path.
    """

    def __init__(
        self,
        capabilities: type[CapabilityT],
        *,
        environment: Mapping[str, str] | None = None,
        error_factory: ErrorFactory = McpBindingError,
    ) -> None:
        """Initialize the typed loader with the capability catalog and secret source.

        Args:
            capabilities (type[CapabilityT]): Application capabilities valid in server declarations.
            environment (Mapping[str, str] | None): Environment source used for secret references.
            error_factory (ErrorFactory): Callback that builds the domain error for this failure path.
        """
        self._capabilities = capabilities
        self._environment = environment
        self._error_factory = error_factory

    def load(
        self, path: Path, *, name: str = ""
    ) -> McpServerConfiguration[CapabilityT]:
        """Load and validate configuration at ``path`` without opening a connection.

        Args:
            path (Path): MCP server YAML file.
            name (str): Fallback configuration name when the file omits ``server``.
        """
        try:
            source = YamlDocument(path).validate(
                McpServerConfigurationInput,
                schema=ManifestSchemas.mcp_server(),
            )
            binding = McpServerBindingLoader(
                self._capabilities,
                error_factory=self._error_factory,
            ).load(path, name=name)
            api_key = self._resolve_api_key(source, path)
            oauth = self._resolve_oauth(source, path)
            delegated_oauth = self._resolve_delegated_oauth(source, path)
            headers = self._resolve_headers(source.headers, path)
            if api_key is not None:
                headers[api_key.header_name] = api_key.value.get_secret_value()
            return McpServerConfiguration(
                binding=binding,
                request_timeout_seconds=source.request_timeout_seconds,
                authentication_mode=source.authentication_mode,
                api_key=api_key,
                oauth=oauth,
                network=McpNetworkSettings(proxy_url=source.network.proxy_url),
                delegated_oauth=delegated_oauth,
                headers=_RedactedMapping(headers),
            )
        except ConfigurationError as error:
            raise self._error_factory(str(error)) from error

    def _resolve_api_key(
        self,
        source: McpServerConfigurationInput,
        path: Path,
    ) -> McpApiKeySettings | None:
        """Resolve the configured API-key value without echoing it on failure.

        Args:
            source (McpServerConfigurationInput): Validated fields from the YAML document.
            path (Path): Source YAML file named in safe diagnostics.
        """
        credential = source.authentication_api_key
        if credential is None:
            return None
        return McpApiKeySettings(
            header_name=credential.header_name,
            value=SecretStr(
                self._resolve_secret(
                    credential.value, "authentication_api_key.value", path
                )
            ),
        )

    def _resolve_oauth(
        self, source: McpServerConfigurationInput, path: Path
    ) -> McpOAuthSettings | None:
        """Resolve OAuth client credentials and configuration-relative token path.

        Args:
            source (McpServerConfigurationInput): Validated fields from the YAML document.
            path (Path): Source YAML file used to resolve relative token storage.
        """
        oauth = source.authentication_oauth
        if oauth is None:
            return None
        token_path = Path(oauth.token_file)
        if not token_path.is_absolute():
            configuration_root = (
                path.parent.parent.parent if path.parent.name == "mcp" else path.parent
            )
            token_path = configuration_root / token_path
        return McpOAuthSettings(
            client_id=oauth.client_id,
            client_secret=SecretStr(
                self._resolve_secret(
                    oauth.client_secret, "authentication_oauth.client_secret", path
                )
            ),
            callback_port=oauth.callback_port,
            scopes=oauth.scopes,
            token_file=token_path,
            client_name=oauth.client_name,
        )

    def _resolve_delegated_oauth(
        self,
        source: McpServerConfigurationInput,
        path: Path,
    ) -> OAuthTokenExchangeSettings | None:
        """Resolve the OBO client credential and retain typed downstream settings.

        Args:
            source (McpServerConfigurationInput): Validated fields from the YAML document.
            path (Path): Source YAML file named in safe diagnostics.
        """
        settings = source.authentication_oauth_on_behalf_of
        if settings is None:
            return None
        client_secret = None
        if settings.client_secret is not None:
            client_secret = SecretStr(
                self._resolve_secret(
                    settings.client_secret,
                    "authentication_oauth_on_behalf_of.client_secret",
                    path,
                )
            )
        return OAuthTokenExchangeSettings(
            audience=settings.audience,
            scopes=settings.scopes,
            token_url=settings.token_url,
            client_id=settings.client_id,
            client_secret=client_secret,
        )

    def _resolve_headers(self, values: Mapping[str, str], path: Path) -> dict[str, str]:
        """Resolve environment-only header values and retain context templates.

        Args:
            values (Mapping[str, str]): Validated configured header names and values.
            path (Path): Source YAML file named in safe diagnostics.
        """
        resolved: dict[str, str] = {}
        for name, value in values.items():
            if _SECRET_REFERENCE.fullmatch(value) is None:
                resolved[name] = value
                continue
            resolved[name] = self._resolve_secret(value, f"headers.{name}", path)
        return resolved

    def _resolve_secret(self, reference: str, field: str, path: Path) -> str:
        """Resolve one `${ENV_VAR}` reference and report only its field and name.

        Args:
            reference (str): Credential reference from a designated YAML field.
            field (str): Field path used to explain missing or malformed references.
            path (Path): Source YAML file named in safe diagnostics.
        """
        match = _SECRET_REFERENCE.fullmatch(reference)
        if match is None:
            raise self._error_factory(
                f"{path}: {field} must reference a secret as ${{ENV_VAR}}"
            )
        environment = self._environment if self._environment is not None else os.environ
        variable_name = match.group("name")
        value = environment.get(variable_name, "")
        if not value:
            raise self._error_factory(
                f"{path}: {field} references environment variable {variable_name!r}, which is not set"
            )
        return value
